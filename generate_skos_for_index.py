"""Render the versioned index page, the root redirect and the About page.

    templates/index.html       (hand-crafted section headings, Jinja2)
  + child links from the vault (each parent's # Narrower list, D-009)
  + definitions from the vault (# Definition section of each concept note)
  -> <site_dir>/<version>/index.html   the index for this version, with JSON-LD
  -> <site_dir>/index.html             a small page that redirects to /<version>/
  -> <site_dir>/about/index.html       site-level About page (templates/about.html)
  -> <site_dir>/<key>/index.html       permanent concept IRIs (D-006), see below
  -> <site_dir>/concept-scheme/index.html   permanent scheme IRI

D-006: https://vernacular.cloud/<key>/ names the concept itself. The page there is
small: the concept's JSON-LD with dct:hasVersion for every version that has it,
OpenGraph tags for link previews, and an immediate redirect to the latest version.
These pages are rewritten at each release and never deleted, so a concept dropped
from the vault still resolves to the last version that had it.

Run obsidian_to_jsonld.py first, so the version folder exists.
Nothing hand-edited is overwritten: the templates are only read, and the root
index.html and about/index.html are only replaced if they were generated
(or with --force). --no-root also skips the permanent IRI pages.

--about-only re-renders just the About page, e.g. after editing its template,
without touching a published (frozen) <version>/index.html.
"""
import argparse
import json
import re
import sys
from pathlib import Path
from urllib.parse import urljoin

import frontmatter
from bs4 import BeautifulSoup
from jinja2 import Environment, FileSystemLoader
from vault_clean import clean_lines, before_wip

# --- CONFIGURATION (all values come from config.toml via vc_config.py) ---
from vc_config import (
    DOMAIN, VERSION, VAULT_DIR, SITE_DIR, OUTPUT_DIR, TEMPLATE_DIR,
    VERSION_URL, SCHEME_IRI, SCHEME_PAGE_URL, ROOT_CONCEPT_IRI,
    KEY_PATTERN, VERSION_PATTERN, JSONLD_CONTEXT, concept_iri, page_url,
)

INDEX_TEMPLATE = "index.html"
ROOT_TEMPLATE = "root_redirect.html"
ABOUT_TEMPLATE = "about.html"
IRI_TEMPLATE = "stable_iri.html"
ROOT_MARKER = "generated by generate_skos_for_index.py"


# --- DEFINITIONS FROM THE VAULT ---

def normalize_text(text_lines):
    """Join definition lines into one plain-text string for skos:definition."""
    if not text_lines:
        return None
    text = " ".join(line.strip() for line in text_lines if line.strip())
    text = re.sub(r'!\[\[[^\]]*\]\]', '', text)                    # drop embeds  ![[note#^block]]
    text = re.sub(r'\[\[(?:[^\]|]*\|)?([^\]]*)\]\]', r'\1', text)  # [[target|alias]] -> alias, [[x]] -> x
    text = re.sub(r'\s{2,}', ' ', text).strip()
    return text or None


def parse_definition_from_md(content):
    capturing = False
    definition_lines = []
    for line in content.split('\n'):
        header_match = re.match(r'^#+\s+(.*)', line)
        if header_match:
            if header_match.group(1).strip().lower() == "definition":
                capturing = True
                continue
            elif capturing:
                break
        if capturing:
            definition_lines.append(line)
    return normalize_text(clean_lines(definition_lines))


def build_definition_map(source_dir):
    print(f"📂 Scanning Markdown files in {source_dir}...")
    def_map = {}
    for file_path in Path(source_dir).glob("*.md"):
        try:
            post = frontmatter.load(file_path)
        except Exception as e:
            print(f"   ⚠️ Could not read {file_path.name}: {e}")
            continue
        uuid = post.metadata.get('concept-key')
        if uuid:
            definition = parse_definition_from_md(before_wip(post.content))
            if definition:
                def_map[uuid] = definition
    print(f"✅ Indexed {len(def_map)} definitions.")
    return def_map


# --- CONCEPT DATA FOR THE TEMPLATE'S section() MACRO ---

def build_concepts(vault):
    """{key: {"label": vault file name, "narrower": [{"key", "label"}, ...]}}
    for every note with a concept-key; children keep the # Narrower order."""
    import sync_hierarchy
    notes, resolve = sync_hierarchy.load(vault)
    concepts, skipped = {}, []
    for n in notes.values():
        if not n.key:
            continue
        kids = []
        for name in n.links("narrower"):
            c = resolve(name)
            if c and c.key and c.stem != n.stem:
                kids.append({"key": c.key, "label": c.stem})
            else:
                skipped.append(f"{n.stem} → [[{name}]]")
        concepts[n.key] = {"label": n.stem, "narrower": kids}
    return concepts, skipped


def check_section_keys(template_text, concepts):
    keys = re.findall(r'section\("([A-Za-z0-9_-]{24})"', template_text)
    missing = [k for k in keys if k not in concepts]
    for k in missing:
        print(f"   ⚠️ templates/index.html: section key {k} has no note in the vault")
    return keys


# --- JSON-LD FROM THE RENDERED SECTION STRUCTURE ---

def absolute_uri(href):
    """IRI for a link in the template.

    'key/' -> https://vernacular.cloud/key/   (a concept: its permanent IRI, D-006)
    '/x/'  -> https://vernacular.cloud/x/
    other relative links resolve against this version's folder.
    """
    if re.fullmatch(KEY_PATTERN + "/?", href):
        return concept_iri(href.rstrip("/"))
    return urljoin(VERSION_URL + "/", href)


def key_from_uri(uri):
    parts = uri.strip('/').split('/')
    return parts[-1] if parts else None


def build_jsonld(template_text, definition_map):
    soup = BeautifulSoup(template_text, "html.parser")
    main_area = soup.find("main")
    if not main_area:
        sys.exit("❌ No <main> element in templates/index.html")

    graph_map = {}
    for section in main_area.find_all("section"):
        header = section.find("header")
        h1 = header.find("h1") if header else None
        parent_link = h1.find("a") if h1 else None
        if not parent_link or not parent_link.get("href"):
            continue

        parent_uri = absolute_uri(parent_link["href"])
        parent_key = key_from_uri(parent_uri)

        # Visible heading vs data-pref-label: the attribute holds skos:prefLabel,
        # the visible text ("The Unsayables") becomes skos:altLabel.
        visible_text = parent_link.get_text(strip=True)
        hidden_pref = parent_link.get("data-pref-label")
        pref_label = hidden_pref or visible_text
        alt_label = visible_text if hidden_pref else None

        narrower_uris = []
        for p in section.find_all("p", recursive=False):
            child_link = p.find("a")
            if child_link and child_link.get("href"):
                narrower_uris.append(absolute_uri(child_link["href"]))

        if parent_uri in graph_map:
            if narrower_uris:
                existing = graph_map[parent_uri].get("skos:narrower", [])
                graph_map[parent_uri]["skos:narrower"] = existing + [u for u in narrower_uris if u not in existing]
            continue

        concept = {
            "@id": parent_uri,
            "@type": "skos:Concept",
            "skos:prefLabel": pref_label,
            "skos:inScheme": SCHEME_IRI,
            "skos:broader": ROOT_CONCEPT_IRI,
        }
        if alt_label:
            concept["skos:altLabel"] = alt_label
        if parent_key in definition_map:
            concept["skos:definition"] = definition_map[parent_key]
        if narrower_uris:
            concept["skos:narrower"] = narrower_uris
        graph_map[parent_uri] = concept

    return {
        "@context": JSONLD_CONTEXT,
        "@graph": list(graph_map.values()) + [
            {"@id": VERSION_URL + "/", "owl:versionInfo": VERSION},
        ],
    }


# --- PERMANENT IRIs (D-006) ---

def _vkey(v):
    return tuple(int(x) for x in v.split("."))


def published_versions():
    """Version folders in the site repo, oldest first."""
    return sorted((d.name for d in SITE_DIR.iterdir()
                   if d.is_dir() and re.fullmatch(VERSION_PATTERN, d.name)), key=_vkey)


def page_facts(html_file):
    """(label, description) read back from a generated concept page."""
    text = html_file.read_text(encoding="utf-8", errors="replace")
    t = re.search(r"<title>(.*?) - Vernacular Cloud</title>", text, re.S)
    d = re.search(r'<meta name="description" content="(.*?)"', text, re.S)
    desc = BeautifulSoup(d.group(1), "html.parser").get_text() if d else None
    if desc == "vernacular cloud taxonomy with json-ld":   # generic text on pages before 0.0.4
        desc = None
    return (t.group(1).strip() if t else None, desc)


def write_stable_iri_pages(env, force):
    """Write <site_dir>/<key>/index.html for every concept in any version, and
    <site_dir>/concept-scheme/index.html. Returns the number of pages written."""
    versions = published_versions()
    history = {}                                   # key -> [versions that have it]
    for v in versions:
        for d in (SITE_DIR / v).iterdir():
            if d.is_dir() and re.fullmatch(KEY_PATTERN, d.name) and (d / "index.html").exists():
                history.setdefault(d.name, []).append(v)

    # Windows folders ignore case: two keys differing only in case would share a folder.
    seen = {}
    for k in history:
        if k.casefold() in seen:
            print(f"   ⚠️ keys differ only in case: {seen[k.casefold()]} / {k} (share a folder on Windows)")
        seen[k.casefold()] = k

    template = env.get_template(IRI_TEMPLATE)
    written = skipped = 0
    for key, vs in sorted(history.items()):
        latest = vs[-1]
        label, description = page_facts(SITE_DIR / latest / key / "index.html")
        label = label or key
        jsonld = {
            "@context": JSONLD_CONTEXT,
            "@id": concept_iri(key),
            "@type": "skos:Concept",
            "skos:prefLabel": label,
            "skos:inScheme": SCHEME_IRI,
            "dct:hasVersion": [page_url(key, v) for v in vs],
        }
        if _write_generated(SITE_DIR / key / "index.html", force, template.render(
                marker=ROOT_MARKER, iri=concept_iri(key), label=label,
                description=description or f"{label}: a concept in the Vernacular Cloud nomenclature.",
                latest=latest, versions=vs,
                latest_path=f"/{latest}/{key}/", key=key,
                json_ld=json.dumps(jsonld, indent=2, ensure_ascii=False))):
            written += 1
        else:
            skipped += 1

    scheme_versions = [v for v in versions if (SITE_DIR / v / "concept-scheme" / "index.html").exists()]
    if scheme_versions:
        latest = scheme_versions[-1]
        jsonld = {
            "@context": JSONLD_CONTEXT,
            "@id": SCHEME_IRI,
            "@type": "skos:ConceptScheme",
            "skos:prefLabel": "Vernacular Cloud",
            "owl:versionIRI": f"{DOMAIN}/{latest}/concept-scheme/",
            "dct:hasVersion": [f"{DOMAIN}/{v}/concept-scheme/" for v in scheme_versions],
        }
        if _write_generated(SITE_DIR / "concept-scheme" / "index.html", force, template.render(
                marker=ROOT_MARKER, iri=SCHEME_IRI, label="Concept Scheme",
                description="The top concepts of the Badinagean nomenclature, published as SKOS in JSON-LD.",
                latest=latest, versions=scheme_versions,
                latest_path=f"/{latest}/concept-scheme/", key="concept-scheme",
                json_ld=json.dumps(jsonld, indent=2, ensure_ascii=False))):
            written += 1

    print(f"✅ Permanent IRIs: {written} pages at /<key>/ and /concept-scheme/"
          + (f" ({skipped} skipped)" if skipped else ""))
    return written


def _write_generated(path, force, html):
    """Write a generated page, but never over a file this script didn't generate."""
    if path.exists() and not force and ROOT_MARKER not in path.read_text(encoding="utf-8", errors="replace"):
        print(f"   ⚠️ {path} was not generated; NOT replaced (use --force).")
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(html, encoding="utf-8")
    return True


# --- RENDERING ---

def write_root_redirect(env, force):
    root_file = SITE_DIR / "index.html"
    if root_file.exists() and not force:
        existing = root_file.read_text(encoding="utf-8", errors="replace")
        if ROOT_MARKER not in existing:
            print(f"⚠️ {root_file} is not a generated redirect (probably the old hand-crafted index).")
            print("   Move it into its version folder first, or run again with --force to replace it.")
            print("   Root redirect NOT written.")
            return False
    html = env.get_template(ROOT_TEMPLATE).render(version=VERSION, domain=DOMAIN, marker=ROOT_MARKER)
    root_file.write_text(html, encoding="utf-8")
    print(f"✅ Root redirect: / -> /{VERSION}/  ({root_file})")
    return True


def write_about_page(env, force):
    about_file = SITE_DIR / "about" / "index.html"
    if about_file.exists() and not force:
        existing = about_file.read_text(encoding="utf-8", errors="replace")
        if ROOT_MARKER not in existing:
            print(f"⚠️ {about_file} is not generated (probably the old hand-written page).")
            print("   Run again with --force to replace it with templates/about.html.")
            print("   About page NOT written.")
            return False
    html = env.get_template(ABOUT_TEMPLATE).render(version=VERSION, domain=DOMAIN, marker=ROOT_MARKER)
    about_file.parent.mkdir(parents=True, exist_ok=True)
    about_file.write_text(html, encoding="utf-8")
    print(f"✅ About page for {VERSION}: {about_file}")
    return True


def main():
    parser = argparse.ArgumentParser(description="Render <version>/index.html, the root redirect and the About page.")
    parser.add_argument("--force", action="store_true",
                        help="replace root index.html / about/index.html even if they were not generated")
    parser.add_argument("--no-root", action="store_true",
                        help="only write <version>/index.html; leave the root index.html, About page and permanent IRI pages alone")
    parser.add_argument("--about-only", action="store_true",
                        help="only write about/index.html; leave <version>/index.html and the root alone")
    args = parser.parse_args()

    print(f"🔖 Version {VERSION}")
    env = Environment(loader=FileSystemLoader(str(TEMPLATE_DIR)))

    if args.about_only:
        write_about_page(env, args.force)
        return

    if not OUTPUT_DIR.is_dir():
        sys.exit(f"❌ {OUTPUT_DIR} not found. Run obsidian_to_jsonld.py for version {VERSION} first.")

    template_text = (TEMPLATE_DIR / INDEX_TEMPLATE).read_text(encoding="utf-8")

    definition_map = build_definition_map(VAULT_DIR)
    concepts, skipped = build_concepts(VAULT_DIR)
    keys = check_section_keys(template_text, concepts)
    used = {k for k in keys if k in concepts}
    for line in skipped:
        parent = line.split(" → ")[0]
        if any(concepts[k]["label"] == parent for k in used):
            print(f"   ⚠️ not on the index (no concept-key or no such note): {line}")

    # Render once to get the section structure, then again with the JSON-LD.
    template = env.get_template(INDEX_TEMPLATE)
    draft = template.render(version=VERSION, domain=DOMAIN, concepts=concepts, json_ld="{}")
    json_ld = build_jsonld(draft, definition_map)
    html = template.render(
        version=VERSION,
        domain=DOMAIN,
        concepts=concepts,
        json_ld=json.dumps(json_ld, indent=2, ensure_ascii=False),
    )
    out_file = OUTPUT_DIR / "index.html"
    out_file.write_text(html, encoding="utf-8")
    print(f"✅ Index for {VERSION}: {len(json_ld['@graph'])} sections -> {out_file}")

    if not args.no_root:
        write_root_redirect(env, args.force)
        write_about_page(env, args.force)
        write_stable_iri_pages(env, args.force)


if __name__ == "__main__":
    main()
