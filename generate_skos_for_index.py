"""Render the versioned index page, the root redirect and the About page.

    templates/index.html       (hand-crafted section structure, Jinja2)
  + definitions from the vault (# Definition section of each concept note)
  -> <site_dir>/<version>/index.html   the index for this version, with JSON-LD
  -> <site_dir>/index.html             a small page that redirects to /<version>/
  -> <site_dir>/about/index.html       site-level About page (templates/about.html)

Run obsidian_to_jsonld.py first, so the version folder exists.
Nothing hand-edited is overwritten: the templates are only read, and the root
index.html and about/index.html are only replaced if they were generated
(or with --force).

--about-only re-renders just the About page, e.g. after editing its template,
without touching a published (frozen) <version>/index.html.
"""
import argparse
import json
import re
import sys
from pathlib import Path
from urllib.parse import urljoin

import frontmatter
from bs4 import BeautifulSoup
from jinja2 import Environment, FileSystemLoader

# --- CONFIGURATION (all values come from config.toml via vc_config.py) ---
from vc_config import (
    DOMAIN, VERSION, VAULT_DIR, SITE_DIR, OUTPUT_DIR, TEMPLATE_DIR,
    VERSION_URL, SCHEME_URI, ROOT_CONCEPT_URI,
)

INDEX_TEMPLATE = "index.html"
ROOT_TEMPLATE = "root_redirect.html"
ABOUT_TEMPLATE = "about.html"
ROOT_MARKER = "generated by generate_skos_for_index.py"


# --- DEFINITIONS FROM THE VAULT ---

def normalize_text(text_lines):
    """Join definition lines into one plain-text string for skos:definition."""
    if not text_lines:
        return None
    text = " ".join(line.strip() for line in text_lines if line.strip())
    text = re.sub(r'!\[\[[^\]]*\]\]', '', text)                    # drop embeds  ![[note#^block]]
    text = re.sub(r'\[\[(?:[^\]|]*\|)?([^\]]*)\]\]', r'\1', text)  # [[target|alias]] -> alias, [[x]] -> x
    text = re.sub(r'\s{2,}', ' ', text).strip()
    return text or None


def parse_definition_from_md(content):
    capturing = False
    definition_lines = []
    for line in content.split('\n'):
        header_match = re.match(r'^#+\s+(.*)', line)
        if header_match:
            if header_match.group(1).strip().lower() == "definition":
                capturing = True
                continue
            elif capturing:
                break
        if capturing:
            definition_lines.append(line)
    return normalize_text(definition_lines)


def build_definition_map(source_dir):
    print(f"📂 Scanning Markdown files in {source_dir}...")
    def_map = {}
    for file_path in Path(source_dir).glob("*.md"):
        try:
            post = frontmatter.load(file_path)
        except Exception as e:
            print(f"   ⚠️ Could not read {file_path.name}: {e}")
            continue
        uuid = post.metadata.get('concept-key')
        if uuid:
            definition = parse_definition_from_md(post.content)
            if definition:
                def_map[uuid] = definition
    print(f"✅ Indexed {len(def_map)} definitions.")
    return def_map


# --- JSON-LD FROM THE TEMPLATE'S SECTION STRUCTURE ---

def absolute_uri(href):
    """Resolve a link in the template against this version's folder.

    'key/' -> https://vernacular.cloud/<version>/key/   (relative, the normal case)
    '/x/'  -> https://vernacular.cloud/x/
    """
    return urljoin(VERSION_URL + "/", href)


def key_from_uri(uri):
    parts = uri.strip('/').split('/')
    return parts[-1] if parts else None


def build_jsonld(template_text, definition_map):
    soup = BeautifulSoup(template_text, "html.parser")
    main_area = soup.find("main")
    if not main_area:
        sys.exit("❌ No <main> element in templates/index.html")

    graph_map = {}
    for section in main_area.find_all("section"):
        header = section.find("header")
        h1 = header.find("h1") if header else None
        parent_link = h1.find("a") if h1 else None
        if not parent_link or not parent_link.get("href"):
            continue

        parent_uri = absolute_uri(parent_link["href"])
        parent_key = key_from_uri(parent_uri)

        # Visible heading vs data-pref-label: the attribute holds skos:prefLabel,
        # the visible text ("The Unsayables") becomes skos:altLabel.
        visible_text = parent_link.get_text(strip=True)
        hidden_pref = parent_link.get("data-pref-label")
        pref_label = hidden_pref or visible_text
        alt_label = visible_text if hidden_pref else None

        narrower_uris = []
        for p in section.find_all("p", recursive=False):
            child_link = p.find("a")
            if child_link and child_link.get("href"):
                narrower_uris.append(absolute_uri(child_link["href"]))

        if parent_uri in graph_map:
            if narrower_uris:
                existing = graph_map[parent_uri].get("skos:narrower", [])
                graph_map[parent_uri]["skos:narrower"] = existing + [u for u in narrower_uris if u not in existing]
            continue

        concept = {
            "@id": parent_uri,
            "@type": "skos:Concept",
            "skos:prefLabel": pref_label,
            "skos:inScheme": SCHEME_URI,
            "skos:broader": ROOT_CONCEPT_URI,
        }
        if alt_label:
            concept["skos:altLabel"] = alt_label
        if parent_key in definition_map:
            concept["skos:definition"] = definition_map[parent_key]
        if narrower_uris:
            concept["skos:narrower"] = narrower_uris
        graph_map[parent_uri] = concept

    return {
        "@context": {
            "skos": "http://www.w3.org/2004/02/skos/core#",
            "dct": "http://purl.org/dc/terms/",
        },
        "@graph": list(graph_map.values()),
    }


# --- RENDERING ---

def write_root_redirect(env, force):
    root_file = SITE_DIR / "index.html"
    if root_file.exists() and not force:
        existing = root_file.read_text(encoding="utf-8", errors="replace")
        if ROOT_MARKER not in existing:
            print(f"⚠️ {root_file} is not a generated redirect (probably the old hand-crafted index).")
            print("   Move it into its version folder first, or run again with --force to replace it.")
            print("   Root redirect NOT written.")
            return False
    html = env.get_template(ROOT_TEMPLATE).render(version=VERSION, domain=DOMAIN, marker=ROOT_MARKER)
    root_file.write_text(html, encoding="utf-8")
    print(f"✅ Root redirect: / -> /{VERSION}/  ({root_file})")
    return True


def write_about_page(env, force):
    about_file = SITE_DIR / "about" / "index.html"
    if about_file.exists() and not force:
        existing = about_file.read_text(encoding="utf-8", errors="replace")
        if ROOT_MARKER not in existing:
            print(f"⚠️ {about_file} is not generated (probably the old hand-written page).")
            print("   Run again with --force to replace it with templates/about.html.")
            print("   About page NOT written.")
            return False
    html = env.get_template(ABOUT_TEMPLATE).render(version=VERSION, domain=DOMAIN, marker=ROOT_MARKER)
    about_file.parent.mkdir(parents=True, exist_ok=True)
    about_file.write_text(html, encoding="utf-8")
    print(f"✅ About page for {VERSION}: {about_file}")
    return True


def main():
    parser = argparse.ArgumentParser(description="Render <version>/index.html, the root redirect and the About page.")
    parser.add_argument("--force", action="store_true",
                        help="replace root index.html / about/index.html even if they were not generated")
    parser.add_argument("--no-root", action="store_true",
                        help="only write <version>/index.html; leave the root index.html and About page alone")
    parser.add_argument("--about-only", action="store_true",
                        help="only write about/index.html; leave <version>/index.html and the root alone")
    args = parser.parse_args()

    print(f"🔖 Version {VERSION}")
    env = Environment(loader=FileSystemLoader(str(TEMPLATE_DIR)))

    if args.about_only:
        write_about_page(env, args.force)
        return

    if not OUTPUT_DIR.is_dir():
        sys.exit(f"❌ {OUTPUT_DIR} not found. Run obsidian_to_jsonld.py for version {VERSION} first.")

    template_text = (TEMPLATE_DIR / INDEX_TEMPLATE).read_text(encoding="utf-8")

    definition_map = build_definition_map(VAULT_DIR)
    json_ld = build_jsonld(template_text, definition_map)

    html = env.get_template(INDEX_TEMPLATE).render(
        version=VERSION,
        domain=DOMAIN,
        json_ld=json.dumps(json_ld, indent=2, ensure_ascii=False),
    )
    out_file = OUTPUT_DIR / "index.html"
    out_file.write_text(html, encoding="utf-8")
    print(f"✅ Index for {VERSION}: {len(json_ld['@graph'])} sections -> {out_file}")

    if not args.no_root:
        write_root_redirect(env, args.force)
        write_about_page(env, args.force)


if __name__ == "__main__":
    main()
